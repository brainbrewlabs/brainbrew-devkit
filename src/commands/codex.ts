export const CODEX_TOOL_MATCHER = 'Write|Edit|MultiEdit|Bash|Agent|Task|task|apply_patch|exec_command|spawn_agent|wait_agent';
const BRAINBREW_MARKER = '<!-- Generated by brainbrew-devkit for Codex.';
const MANIFEST_RELATIVE_PATH = join('brainbrew', 'skills-manifest.json');

type CodexHook = {
  type: 'command';
  command: string;
  timeout: number;
};

type CodexHookEntry = {
  matcher: string;
  hooks: CodexHook[];
};

